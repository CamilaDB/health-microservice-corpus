def dataframe_to_markdown(df: pd.DataFrame) -> str:
    if df.empty:
        return "| Sem dados |"

    headers = [str(column) for column in df.columns]
    rows = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]

    for _, row in df.iterrows():
        values = ["" if pd.isna(value) else str(value) for value in row.tolist()]
        rows.append("| " + " | ".join(values) + " |")

    return "\n".join(rows)


def build_article_markdown(
    summary: pd.DataFrame,
    ccm_summary: pd.DataFrame,
    h2_table: pd.DataFrame,
    h2_mutation_table: pd.DataFrame | None = None,
) -> str:
    lines = [
        "# Resumo da análise experimental",
        "",
        "## 1. Visão geral por modelo e estratégia",
        "",
        "`verified_success_rate` é a métrica corrigida (exclui observações totalmente "
        "skip-repaired); `raw_jest_success_rate` é preservada apenas para rastreabilidade.",
        "",
        dataframe_to_markdown(summary),
        "",
        "## 2. Tendência por faixa de complexidade (todos os modelos agregados)",
        "",
        dataframe_to_markdown(ccm_summary),
        "",
        "## 3. H2 -- complexidade x modelo (cobertura de statements/branches)",
        "",
        "Evidência primária de H2 (Opção C): cobertura por modelo × estratégia × faixa de CCM, "
        "sobre observações de sucesso verificado. `attempted_observations` inclui tudo; "
        "`fully_skipped_observations` são não mensuráveis (não zero); as colunas de cobertura "
        "vêm apenas de `verified_observations`. Ver `docs/experimental-workflow.md` para o "
        "achado negativo da Opção A (assertion roulette).",
        "",
        dataframe_to_markdown(h2_table),
        "",
    ]
    if h2_mutation_table is not None and not h2_mutation_table.empty:
        lines += [
            "## 4. H2 -- complexidade x modelo (mutation score, evidência complementar)",
            "",
            "`mutation_function_results.csv` mapeia cada mutante Stryker à função-alvo que o "
            "contém (via `location`), não ao módulo inteiro -- por isso, ao contrário do "
            "`mutation_results.csv` bruto (uma linha por módulo, que cobre várias faixas de CCM), "
            "esta tabela é uma agregação genuína por função, ponderada por mutante "
            "(soma de killed/survived/no_coverage/timeout antes de calcular a taxa, nunca a média "
            "não ponderada das taxas por função). `mutants_killed_by_own_tests` isola os kills "
            "atribuíveis aos próprios testes da função (via `killedBy` e o marcador "
            "`FN_<função>_END` no nome do teste), separando-os de kills por testes de uma função "
            "irmã no mesmo módulo. Ver a coluna `distinct_functions` para o tamanho amostral de "
            "cada célula -- as faixas `11-20` e `>20` têm poucas funções distintas (5 e 3 de 25) e "
            "devem ser lidas com essa ressalva.",
            "",
            dataframe_to_markdown(h2_mutation_table),
            "",
        ]
    return "\n".join(lines)


def generate_analysis_report() -> dict[str, Path]:
    df = load_results()
    outputs = export_summary_tables(df)
    fig_outputs = export_figures(df)
    outputs.update(fig_outputs)

    smell_df = load_smell_results()
    smell_outputs = export_smell_tables(smell_df)
    smell_figures = export_smell_figures(smell_df)
    outputs.update(smell_outputs)
    outputs.update(smell_figures)

    mutation_df = load_mutation_results()
    function_mutation_df = load_function_mutation_results()
    mutation_outputs = export_mutation_tables(mutation_df, function_mutation_df)
    mutation_figures = export_mutation_figures(mutation_df, function_mutation_df)
    outputs.update(mutation_outputs)
    outputs.update(mutation_figures)

    error_df_raw = load_error_events()
    error_df = build_reclassified_error_events(error_df_raw)
    error_outputs = export_error_event_tables(error_df)
    outputs.update(error_outputs)
    failure_modes_fig = ERROR_OUTPUT_DIR / "failure_modes.png"
    if not error_df.empty:
        ERROR_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
        plot_failure_modes(error_df, failure_modes_fig)
        outputs["failure_modes"] = failure_modes_fig

    summary = build_summary_by_model_strategy(df)
    ccm_summary = build_summary_by_ccm(df)
    h2_table = build_h2_coverage_table(df)
    h2_mutation_table = build_h2_mutation_by_ccm_model(function_mutation_df) if not function_mutation_df.empty else pd.DataFrame()
    markdown_path = OUTPUT_DIR / "article_summary.md"
    markdown_path.write_text(
        build_article_markdown(summary, ccm_summary, h2_table, h2_mutation_table), encoding="utf-8"
    )
    outputs["article_summary"] = markdown_path

    if not smell_df.empty:
        smell_md = OUTPUT_DIR / "smell_summary.md"
        smell_md.write_text(
            "# Test smell summary\n\n" + dataframe_to_markdown(build_smell_summary_by_model_strategy(smell_df)),
            encoding="utf-8",
        )
        outputs["smell_summary"] = smell_md

    if not mutation_df.empty:
        mutation_md = OUTPUT_DIR / "mutation_summary.md"
        mutation_md.write_text(
            "# Mutation summary (corrected, coverage-inclusive, mutant-weighted)\n\n"
            + dataframe_to_markdown(build_mutation_summary_by_model_strategy(mutation_df)),
            encoding="utf-8",
        )
        outputs["mutation_summary"] = mutation_md

    if not error_df.empty:
        reclassified_count = count_reclassified_events(error_df)
        error_md = OUTPUT_DIR / "error_summary.md"
        error_md.write_text(
            "# Error event summary\n\n"
            "Supplementary diagnostic evidence about failure modes -- "
            "**not** a primary outcome metric. error_category/error_subcategory "
            "below are the Phase-3 RECLASSIFIED values "
            f"({reclassified_count} events reclassified away from 'unknown'); "
            "the original, unmodified classification from error_events.csv is "
            "preserved in error_category_original/error_subcategory_original. "
            "See experiments/README.md for the two rate denominators "
            "(events_per_function, events_per_attempt).\n\n"
            "## Most common failure modes by model x strategy\n\n"
            + dataframe_to_markdown(build_top_failure_modes(error_df))
            + "\n\n## Repeated error signatures (same error_hash, >=2 occurrences)\n\n"
            + dataframe_to_markdown(build_repeated_error_signatures(error_df))
            + "\n\n## Events by model x strategy\n\n"
            + dataframe_to_markdown(build_error_summary_by_model_strategy(error_df))
            + "\n\n## Events by phase\n\n"
            + dataframe_to_markdown(build_error_summary_by_phase(error_df)),
            encoding="utf-8",
        )
        outputs["error_summary"] = error_md

    return outputs


if __name__ == "__main__":
    generate_analysis_report()
    print("Analysis artefacts generated at:")
    for path in sorted(OUTPUT_DIR.glob("**/*")):
        if path.is_file():
            print(path.relative_to(ROOT_DIR))
