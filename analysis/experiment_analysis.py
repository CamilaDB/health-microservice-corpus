"""
Single source of truth for post-experiment analysis.

Everything downstream -- the static tables/figures generated by this
script's __main__, and the Streamlit dashboard (analysis/dashboard.py) --
must go through the load_*/build_* functions in this module. Nothing here
mutates the frozen raw artifacts under experiments/metrics/; every
correction described below is a derived column or a separately-aggregated
summary computed from the preserved raw counts.

Two corrections were applied after a post-experiment audit found that the
raw pipeline's own success/score labels do not mean what a reader would
assume for a subset of observations. Both are analysis-layer fixes only:

1. "verified_eligible" (see load_results): a function whose entire
   generated test block was skip-repaired away still reports
   jest_success == True / artifact_disposition == "accepted" in
   results.csv, because Jest exits 0 when nothing *fails* -- including a
   block where everything is it.skip(). analysis_eligible (as stored) does
   not distinguish this from a genuinely verified pass. verified_eligible
   does, using only already-stored columns (passed_tests).

2. "mutation_score_corrected" (see load_mutation_results): the stored
   mutation_score excludes no-coverage mutants from its denominator
   (runner/execution/stryker_runner.py), which silently inflates the score
   exactly where coverage is worst. The corrected, coverage-inclusive,
   mutant-weighted score is computed here from the raw per-status counts,
   which are fully preserved in mutation_results.csv.

See docs/experimental-workflow.md and experiments/README.md for the
narrative explanation of both corrections.
"""
