def _mutation_covered_denominator(df: pd.DataFrame) -> pd.Series:
    """
    killed + survived + no_coverage + timeout.

    compile_error is explicitly EXCLUDED from both the original stored
    score and this corrected one: a mutant that failed to compile was
    never a valid probe of the test suite, in either convention. This
    dataset has zero compile_error mutants throughout, so the choice has
    no numeric effect here, but it is stated explicitly rather than left
    implicit, per the audit's requirement not to silently include or
    exclude it.
    """
    return (
        df["mutants_killed"].fillna(0)
        + df["mutants_survived"].fillna(0)
        + df["mutants_no_coverage"].fillna(0)
        + df["mutants_timeout"].fillna(0)
    )


def load_mutation_results(csv_path: Path = MUTATION_RESULTS_CSV, enforce_single_run: bool = True) -> pd.DataFrame:
    """
    Adds two derived, coverage-inclusive columns computed from the raw,
    unmodified per-status mutant counts:

      - mutation_score_corrected: killed / (killed+survived+no_coverage+
        timeout) * 100. The stored `mutation_score` column
        (runner/execution/stryker_runner.py) uses killed/(killed+survived+
        timeout) instead -- it excludes no_coverage mutants from the
        denominator entirely, which inflates the score wherever coverage
        is weak. `mutation_score` is preserved unchanged for traceability;
        `mutation_score_corrected` is the metric to report.
      - no_coverage_share: mutants_no_coverage / mutants_total * 100 --
        essential context for interpreting either score (see docstring at
        the top of this module).
    """
    if not csv_path.exists():
        return pd.DataFrame()

    df = pd.read_csv(csv_path)
    if df.empty:
        return df
    if enforce_single_run:
        df = _enforce_single_run(df, "mutation_results.csv")
    for column in [
        "mutation_score", "mutants_total", "mutants_killed", "mutants_survived",
        "mutants_timeout", "mutants_no_coverage", "mutants_compile_error",
    ]:
        if column in df.columns:
            df[column] = pd.to_numeric(df[column], errors="coerce")

    required = {"mutants_killed", "mutants_survived", "mutants_no_coverage", "mutants_timeout", "mutants_total"}
    if required.issubset(df.columns):
        covered_denom = _mutation_covered_denominator(df)
        df["mutation_score_corrected"] = (
            df["mutants_killed"] / covered_denom.replace(0, float("nan")) * 100
        ).round(2)
        df["no_coverage_share"] = (
            df["mutants_no_coverage"] / df["mutants_total"].replace(0, float("nan")) * 100
        ).round(2)
    return df


def build_mutation_summary_by_model_strategy(df: pd.DataFrame) -> pd.DataFrame:
    """
    Aggregates from RAW mutant counts summed across modules -- a
    mutant-weighted score -- rather than averaging each module's
    percentage unweighted (the original build_mutation_summary_by_model_
    strategy did the latter, silently giving a 73-mutant module the same
    weight as a 360-mutant one).

    Exposes, side by side and unambiguously named:
      - mutation_score_stryker_unweighted_mean: what the previous summary
        reported (mean of the ORIGINAL, no-coverage-excluding, per-module
        mutation_score) -- kept only for traceability against prior
        figures, must not be used for final reporting.
      - mutation_score_corrected: the mutant-weighted, coverage-inclusive
        score to actually report, computed from summed raw counts.
      - no_coverage_share: summed no_coverage / summed total, for the
        same group -- must accompany mutation_score_corrected in any
        figure/caption per the audit.
    """
    columns = [
        "model", "strategy", "modules",
        "mutants_total", "mutants_killed", "mutants_survived", "mutants_timeout",
        "mutants_no_coverage", "mutants_compile_error",
        "no_coverage_share", "mutation_score_corrected",
        "mutation_score_stryker_unweighted_mean",
    ]
    if df.empty:
        return pd.DataFrame(columns=columns)

    keys = ["model", "strategy"]
    summary = df.groupby(keys, dropna=False).agg(
        modules=("module", "nunique"),
        mutants_total=("mutants_total", "sum"),
        mutants_killed=("mutants_killed", "sum"),
        mutants_survived=("mutants_survived", "sum"),
        mutants_timeout=("mutants_timeout", "sum"),
        mutants_no_coverage=("mutants_no_coverage", "sum"),
        mutants_compile_error=("mutants_compile_error", "sum"),
        mutation_score_stryker_unweighted_mean=("mutation_score", "mean"),
    ).reset_index()

    covered_denom = _mutation_covered_denominator(summary)
    summary["mutation_score_corrected"] = (
        summary["mutants_killed"] / covered_denom.replace(0, float("nan")) * 100
    ).round(2)
    summary["no_coverage_share"] = (
        summary["mutants_no_coverage"] / summary["mutants_total"].replace(0, float("nan")) * 100
    ).round(2)
    summary["mutation_score_stryker_unweighted_mean"] = summary["mutation_score_stryker_unweighted_mean"].round(2)
    return summary.sort_values(keys).reset_index(drop=True)[columns]


