def load_results(csv_path: Path = RESULTS_CSV, enforce_single_run: bool = True) -> pd.DataFrame:
    """
    Loads results.csv and adds two derived, analysis-only columns:

      - verified_eligible: analysis_eligible AND passed_tests > 0.
        The corrected population for "did this produce a genuinely
        verified passing test" -- use this, not analysis_eligible alone,
        for any final success-rate reporting.
      - fully_skipped: analysis_eligible is True but every generated test
        was skipped (passed_tests == 0, failed_tests == 0, pending_tests
        == total_tests > 0). A strict subset of analysis_eligible and
        disjoint from verified_eligible.

    analysis_eligible itself is preserved exactly as stored -- its
    original semantics (jest_result exists and succeeded) are untouched;
    verified_eligible/fully_skipped are additional columns, not
    replacements.

    enforce_single_run=False skips the run-id isolation guard, returning
    every run_id present as-is -- for the dashboard's own run selector
    (see analysis/dashboard.py), which needs the full multi-run frame to
    populate its dropdown before the user picks one. The static report
    (build_all_outputs / __main__) always uses the default True.
    """
    if not csv_path.exists():
        raise FileNotFoundError(f"Result CSV not found: {csv_path}")

    df = pd.read_csv(csv_path)
    if enforce_single_run:
        df = _enforce_single_run(df, "results.csv")
    for column in NUMERIC_COLUMNS:
        if column in df.columns:
            df[column] = pd.to_numeric(df[column], errors="coerce")
    if "generation_success" in df.columns:
        df["generation_success"] = _as_bool(df["generation_success"])
    if "jest_success" in df.columns:
        df["jest_success"] = _as_bool(df["jest_success"])
    if "analysis_eligible" in df.columns:
        df["analysis_eligible"] = _as_bool(df["analysis_eligible"])
    else:
        # Legacy rows have no explicit eligibility field. Preserve their
        # original function-level interpretation without counting failures.
        df["analysis_eligible"] = (
            df.get("generation_success", False) & df.get("jest_success", False)
        )
    if "strategy" in df.columns:
        df["strategy"] = df["strategy"].fillna("unknown").astype(str)
    if "model" in df.columns:
        df["model"] = df["model"].fillna("unknown").astype(str)

    if {"analysis_eligible", "passed_tests"}.issubset(df.columns):
        df["verified_eligible"] = df["analysis_eligible"] & (df["passed_tests"].fillna(0) > 0)
    else:
        df["verified_eligible"] = df.get("analysis_eligible", False)

    if {"analysis_eligible", "passed_tests", "failed_tests", "pending_tests", "total_tests"}.issubset(df.columns):
        df["fully_skipped"] = (
            df["analysis_eligible"]
            & (df["passed_tests"].fillna(0) == 0)
            & (df["failed_tests"].fillna(0) == 0)
            & (df["total_tests"].fillna(0) > 0)
            & (df["pending_tests"].fillna(0) == df["total_tests"].fillna(0))
        )
    else:
        df["fully_skipped"] = False

    return df


def build_summary_by_model_strategy(df: pd.DataFrame) -> pd.DataFrame:
    """
    Primary model x strategy reporting table. Distinguishes four
    populations explicitly (all derivable from the frozen results.csv):

      - observations_attempted  : every row (one per target function)
      - raw_jest_success_rate   : jest_success == True as STORED -- kept
                                   for traceability only; INCLUDES
                                   fully-skipped observations, so this is
                                   not the corrected success rate.
      - fully_skipped_count     : observations where every generated test
                                   was skipped away (see load_results).
      - verified_eligible_count / verified_success_rate: the corrected,
        final-reported population and rate.

    mean_*/median_* test-count and coverage columns are computed over
    verified_eligible observations, not analysis_eligible -- this is the
    "recompute final reported denominators using the corrected
    definition" change from the post-experiment audit.
    """
    keys = ["model", "strategy"]
    attempted = (
        df.groupby(keys, dropna=False)
        .agg(
            observations_attempted=("function", "size"),
            generation_success_rate=("generation_success", "mean"),
            raw_jest_success_rate=("jest_success", "mean"),
            fully_skipped_count=("fully_skipped", "sum"),
            verified_eligible_count=("verified_eligible", "sum"),
        )
        .reset_index()
    )
    verified = df[df["verified_eligible"]].copy()
    grouped = verified.groupby(keys, dropna=False)
    summary = grouped.agg(
        functions_evaluated=("function", "nunique"),
        mean_total_tests=("total_tests", "mean"),
        median_total_tests=("total_tests", "median"),
        mean_passed_tests=("passed_tests", "mean"),
        mean_failed_tests=("failed_tests", "mean"),
        mean_function_coverage=("fn_functions_pct", "mean"),
        median_function_coverage=("fn_functions_pct", "median"),
        mean_statement_coverage=("fn_statements_pct", "mean"),
        mean_branch_coverage=("fn_branches_pct", "mean"),
    ).reset_index().merge(attempted, on=keys, how="outer")

    summary["functions_evaluated"] = summary["functions_evaluated"].fillna(0).astype(int)
    summary["fully_skipped_count"] = summary["fully_skipped_count"].fillna(0).astype(int)
    summary["verified_eligible_count"] = summary["verified_eligible_count"].fillna(0).astype(int)
    summary["generation_success_rate"] = (summary["generation_success_rate"] * 100).round(2)
    summary["raw_jest_success_rate"] = (summary["raw_jest_success_rate"] * 100).round(2)
    summary["verified_success_rate"] = (
        summary["verified_eligible_count"] / summary["observations_attempted"] * 100
    ).round(2)
    for col in (
        "mean_total_tests", "median_total_tests", "mean_passed_tests", "mean_failed_tests",
        "mean_function_coverage", "median_function_coverage",
        "mean_statement_coverage", "mean_branch_coverage",
    ):
        summary[col] = summary[col].round(2)

    column_order = [
        "model", "strategy",
        "observations_attempted",
        "raw_jest_success_rate", "fully_skipped_count",
        "verified_eligible_count", "verified_success_rate",
        "functions_evaluated", "generation_success_rate",
        "mean_total_tests", "median_total_tests", "mean_passed_tests", "mean_failed_tests",
        "mean_function_coverage", "median_function_coverage",
        "mean_statement_coverage", "mean_branch_coverage",
    ]
    summary = summary[[c for c in column_order if c in summary.columns]]
    return summary.sort_values(["model", "strategy"]).reset_index(drop=True)


def build_summary_by_ccm(df: pd.DataFrame) -> pd.DataFrame:
    """CCM-band summary, computed over verified_eligible observations."""
    empty_cols = ["ccm_band", "functions", "mean_total_tests", "mean_function_coverage",
                  "mean_statement_coverage", "mean_branch_coverage"]
    if "ccm" not in df.columns:
        return pd.DataFrame(columns=empty_cols)

    df_copy = df[df["verified_eligible"]].copy()
    df_copy["ccm_band"] = pd.cut(df_copy["ccm"], bins=CCM_BINS, labels=CCM_LABELS, right=False)
    cc_summary = (
        df_copy.groupby("ccm_band", dropna=False, observed=False)
        .agg(
            functions=("function", "nunique"),
            mean_total_tests=("total_tests", "mean"),
            mean_function_coverage=("fn_functions_pct", "mean"),
            mean_statement_coverage=("fn_statements_pct", "mean"),
            mean_branch_coverage=("fn_branches_pct", "mean"),
        )
        .reset_index()
    )
    for col in ("mean_total_tests", "mean_function_coverage", "mean_statement_coverage", "mean_branch_coverage"):
        cc_summary[col] = cc_summary[col].round(2)
    return cc_summary


def build_ccm_band_population(df: pd.DataFrame) -> pd.DataFrame:
    """
    How many of the 25 target functions fall in each CCM band, regardless
    of outcome -- for labeling small-N bands in figures/captions (a band
    with 2-3 functions needs an explicit sample-size warning).
    """
    if "ccm" not in df.columns or "fn_id" not in df.columns:
        return pd.DataFrame(columns=["ccm_band", "distinct_functions"])
    unique_fns = df.drop_duplicates(subset=["fn_id"]).copy()
    unique_fns["ccm_band"] = pd.cut(unique_fns["ccm"], bins=CCM_BINS, labels=CCM_LABELS, right=False)
    return (
        unique_fns.groupby("ccm_band", dropna=False, observed=False)
        .size()
        .rename("distinct_functions")
        .reset_index()
    )


