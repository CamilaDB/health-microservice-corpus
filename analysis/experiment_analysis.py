def plot_h2_coverage_continuous(df: pd.DataFrame, output_path: Path) -> None:
    """
    Figure H2-B -- continuous complement to H2-A: raw CCM (not banded) on
    the x-axis vs. statement coverage on the y-axis, one point per verified
    observation, colored by model, marker shaped by strategy. With only 25
    underlying functions (each observed up to 3 times, once per strategy),
    this is EXPLORATORY: the per-model line connects mean coverage at each
    observed CCM value as a visual aid only -- it is not a fitted
    regression and no significance is claimed or tested.
    """
    verified = df[df["verified_eligible"]]
    if verified.empty or "ccm" not in verified.columns:
        return

    markers = {"zero_shot": "o", "few_shot": "s", "structured": "^"}

    fig, ax = plt.subplots(figsize=(10.5, 6.5))
    for model in MODEL_SIZE_ORDER:
        sub = verified[verified["model"] == model]
        if sub.empty:
            continue
        color = MODEL_PALETTE.get(model, "#888888")
        for strategy, marker in markers.items():
            s = sub[sub["strategy"] == strategy]
            if s.empty:
                continue
            ax.scatter(s["ccm"], s["fn_statements_pct"], color=color, marker=marker,
                       alpha=0.55, s=50, edgecolors="none")
        trend = sub.groupby("ccm")["fn_statements_pct"].mean().sort_index()
        ax.plot(trend.index, trend.values, color=color, linewidth=1.8, alpha=0.85,
                label=f"{MODEL_SIZE_LABELS.get(model, model)} (média por CCM, n={len(sub)})")

    from matplotlib.lines import Line2D
    strategy_handles = [
        Line2D([0], [0], marker=m, color="gray", linestyle="None", markersize=7, label=s)
        for s, m in markers.items()
    ]
    model_legend = ax.legend(loc="upper right", fontsize=8, title="Modelo (linha = média por CCM)")
    ax.add_artist(model_legend)
    ax.legend(handles=strategy_handles, loc="lower left", fontsize=8, title="Estratégia (forma do marcador)")

    ax.set_xlabel("CCM (complexidade ciclomática)")
    ax.set_ylabel("Cobertura de statements (%)")
    ax.set_ylim(-5, 112)
    # Sample-size / exploratory-only caveat previously lived in the removed
    # in-image title; kept as a footnote, not a title.
    plt.figtext(
        0.01, 0.01,
        f"n={len(verified)} observações verificadas de 25 funções -- exploratório, sem teste de significância.",
        fontsize=7.5, color="#666",
    )
    apply_thesis_chart_style(ax)
    plt.tight_layout()
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


