# ── Phase 3: diagnostic reclassification of "unknown" events ────────────────
#
# Purely additive and read-only: reads error_message and, when available,
# the preserved raw_artifact_path text (never error_events.csv itself, and
# never any repair-flow input) to attempt a more specific classification
# for events the original pipeline-time classifier left as "unknown".
# error_hash and every original column are untouched; reclassification
# results live in separate *_reclassified columns plus a reason column, so
# the original record remains fully recoverable.

_TOEQUAL_RE = re.compile(r"toEqual[\s\S]{0,80}(?:-\s*Expected|\+\s*Received)")
_ASYNC_UNEXPECTED_THROW_RE = re.compile(
    r"resolved instead of rejected|Received promise resolved", re.IGNORECASE
)
_SUITE_FAILED_RE = re.compile(
    r"Test suite failed to run|Jest encountered an unexpected token|Jest failed to parse a file",
    re.IGNORECASE,
)


def _diagnostic_text(row: pd.Series) -> str:
    """
    Prefers the full raw artifact (when one was preserved) over the
    truncated error_message, since some whole-suite-failure shapes put
    the identifying text past the 500-char truncation point.
    """
    text = str(row.get("error_message") or "")
    path = row.get("raw_artifact_path")
    if isinstance(path, str) and path.strip():
        try:
            full = Path(path).read_text(encoding="utf-8", errors="replace")
            if full:
                text = full
        except OSError:
            pass
    return text


def _reclassify_row(row: pd.Series) -> tuple[str, str, str]:
    original_category = str(row.get("error_category") or "")
    original_subcategory = str(row.get("error_subcategory") or "")
    if original_subcategory != "unknown":
        return original_category, original_subcategory, "unchanged"

    text = _diagnostic_text(row)

    if _SUITE_FAILED_RE.search(text):
        if "error TS" in text:
            category, subcategory = classify_typescript_failure(text)
            return category, subcategory, "suite_failed_to_run:typescript"
        return "jest", "test_discovery_failure", "suite_failed_to_run:no_ts_marker"

    if _TOEQUAL_RE.search(text):
        return "jest", "assertion_failure", "toEqual_deep_equality_diff"

    if _ASYNC_UNEXPECTED_THROW_RE.search(text):
        return "jest", "unexpected_throw", "async_resolved_instead_of_rejected"

    return original_category, original_subcategory, "unchanged"


def reclassify_error_events(df: pd.DataFrame) -> pd.DataFrame:
    """
    Returns df with three added columns: error_category_reclassified,
    error_subcategory_reclassified, reclassification_reason. Rows whose
    original error_subcategory was not "unknown" pass through unchanged
    (reclassified == original, reason == "unchanged"), so this is safe to
    apply unconditionally to the whole log.
    """
    if df.empty or "error_subcategory" not in df.columns:
        return df
    out = df.copy()
    reclassified = out.apply(_reclassify_row, axis=1, result_type="expand")
    out["error_category_reclassified"] = reclassified[0]
    out["error_subcategory_reclassified"] = reclassified[1]
    out["reclassification_reason"] = reclassified[2]
    return out


def build_reclassified_error_events(df: pd.DataFrame) -> pd.DataFrame:
    """
    The dataframe to use for final diagnostic summaries/figures:
    error_category/error_subcategory are overwritten with the reclassified
    values, while error_category_original/error_subcategory_original
    preserve exactly what error_events.csv (on disk, unmodified) recorded.
    """
    out = reclassify_error_events(df)
    if out.empty or "error_category_reclassified" not in out.columns:
        return out
    out["error_category_original"] = out["error_category"]
    out["error_subcategory_original"] = out["error_subcategory"]
    out["error_category"] = out["error_category_reclassified"]
    out["error_subcategory"] = out["error_subcategory_reclassified"]
    return out


def count_reclassified_events(df: pd.DataFrame) -> int:
    """Number of events whose subcategory actually changed away from 'unknown'."""
    if df.empty or "reclassification_reason" not in df.columns:
        return 0
    return int((df["reclassification_reason"] != "unchanged").sum())


def _distinct_attempts(df: pd.DataFrame) -> pd.DataFrame:
    """
    One row per (model, strategy, fn_id, phase, attempt) actually logged --
    the unit the "per attempt" denominator counts. Events with no attempt
    number (pipeline-level events not tied to a numbered generation/repair
    attempt, e.g. a rollback) are excluded from this count on purpose: they
    are not part of the attempt sequence being normalized against.
    """
    if "attempt" not in df.columns:
        return df.iloc[0:0]
    attempted = df.dropna(subset=["attempt"])
    return attempted.drop_duplicates(subset=["model", "strategy", "fn_id", "phase", "attempt"])


def build_error_summary(df: pd.DataFrame, keys: list[str]) -> pd.DataFrame:
    """
    Two denominators, both reported explicitly rather than a single
    implicit "error rate", so raw event counts are never compared alone:

      - functions_observed: distinct fn_id with at least one recorded error
        event within the group.
      - distinct_attempts_logged: distinct (fn_id, phase, attempt)
        combinations within the group -- approximates how many discrete
        generation/repair attempts actually occurred, so two models that
        retry a different number of times are not compared on raw event
        counts alone.

    events_per_function and events_per_attempt are the two corresponding
    rates. Neither is a performance metric; both are diagnostic only.
    """
    empty_columns = [
        *keys, "total_events", "functions_observed", "distinct_attempts_logged",
        "events_per_function", "events_per_attempt",
    ]
    if df.empty:
        return pd.DataFrame(columns=empty_columns)

    total_events = df.groupby(keys, dropna=False).size().rename("total_events")
    functions_observed = (
        df.groupby(keys, dropna=False)["fn_id"].nunique().rename("functions_observed")
    )
    distinct_attempts = (
        _distinct_attempts(df).groupby(keys, dropna=False).size().rename("distinct_attempts_logged")
    )

    summary = pd.concat([total_events, functions_observed, distinct_attempts], axis=1).reset_index()
    summary["functions_observed"] = summary["functions_observed"].fillna(0).astype(int)
    summary["distinct_attempts_logged"] = summary["distinct_attempts_logged"].fillna(0).astype(int)
    summary["events_per_function"] = (
        summary["total_events"] / summary["functions_observed"].replace(0, float("nan"))
    ).round(2)
    summary["events_per_attempt"] = (
        summary["total_events"] / summary["distinct_attempts_logged"].replace(0, float("nan"))
    ).round(2)
    return summary.sort_values(keys).reset_index(drop=True)


def build_error_summary_by_model(df: pd.DataFrame) -> pd.DataFrame:
    return build_error_summary(df, ["model"])


def build_error_summary_by_strategy(df: pd.DataFrame) -> pd.DataFrame:
    return build_error_summary(df, ["strategy"])


def build_error_summary_by_model_strategy(df: pd.DataFrame) -> pd.DataFrame:
    return build_error_summary(df, ["model", "strategy"])


def build_error_summary_by_phase(df: pd.DataFrame) -> pd.DataFrame:
    return build_error_summary(df, ["model", "strategy", "phase"])


def build_error_summary_by_category(df: pd.DataFrame) -> pd.DataFrame:
    return build_error_summary(df, ["model", "strategy", "error_category", "error_subcategory"])


def build_top_failure_modes(df: pd.DataFrame, top_n: int = 5) -> pd.DataFrame:
    """
    Answers "what are the most common failure modes for each model and
    strategy?" -- ranked by event count within each (model, strategy) group.
    Descriptive/diagnostic only, not a performance ranking.
    """
    columns = ["model", "strategy", "phase", "error_category", "error_subcategory", "event_count", "rank"]
    if df.empty:
        return pd.DataFrame(columns=columns)

    grouped = (
        df.groupby(["model", "strategy", "phase", "error_category", "error_subcategory"], dropna=False)
        .size()
        .rename("event_count")
        .reset_index()
    )
    grouped["rank"] = (
        grouped.groupby(["model", "strategy"])["event_count"]
        .rank(method="first", ascending=False)
        .astype(int)
    )
    top = grouped[grouped["rank"] <= top_n].sort_values(["model", "strategy", "rank"])
    return top.reset_index(drop=True)


def build_repeated_error_signatures(df: pd.DataFrame, min_occurrences: int = 2) -> pd.DataFrame:
    """
    Groups by error_hash to surface the same underlying diagnostic
    recurring across attempts/functions -- e.g. a crash that never gets
    repaired because it is never even parsed as a failure, and so recurs
    identically on every retry. Diagnostic only.
    """
    columns = ["error_hash", "model", "strategy", "phase", "error_category",
               "error_subcategory", "occurrences", "distinct_functions", "sample_message"]
    if df.empty or "error_hash" not in df.columns:
        return pd.DataFrame(columns=columns)

    grouped = df.groupby(["error_hash", "model", "strategy", "phase", "error_category", "error_subcategory"], dropna=False).agg(
        occurrences=("error_hash", "size"),
        distinct_functions=("fn_id", "nunique"),
        sample_message=("error_message", "first"),
    ).reset_index()
    grouped = grouped[grouped["occurrences"] >= min_occurrences]
    return grouped.sort_values("occurrences", ascending=False).reset_index(drop=True)[columns]


def export_error_event_tables(df: pd.DataFrame) -> dict[str, Path]:
    """df here is expected to be the RECLASSIFIED log (see
    build_reclassified_error_events) -- callers wanting the untouched
    original should use load_error_events() directly."""
    if df.empty:
        return {}

    ERROR_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    outputs: dict[str, Path] = {}

    tables = {
        "error_summary_by_model": build_error_summary_by_model(df),
        "error_summary_by_strategy": build_error_summary_by_strategy(df),
        "error_summary_by_model_strategy": build_error_summary_by_model_strategy(df),
        "error_summary_by_phase": build_error_summary_by_phase(df),
        "error_summary_by_category": build_error_summary_by_category(df),
        "top_failure_modes": build_top_failure_modes(df),
        "repeated_error_signatures": build_repeated_error_signatures(df),
    }
    for name, table in tables.items():
        path = ERROR_OUTPUT_DIR / f"{name}.csv"
        table.to_csv(path, index=False)
        outputs[name] = path

    return outputs


