def load_latest_run_manifest(run_id: str | None = None) -> dict | None:
    """
    Reads experiments/runs/<run_id>.json. Returns None (never invents
    fields) if no manifest is found. Picks the lexicographically-last
    manifest file when run_id is not given (manifest filenames are
    UTC timestamps, so this is also the most recent run).
    """
    import json

    if not RUN_MANIFEST_DIR.exists():
        return None
    if run_id:
        candidate = RUN_MANIFEST_DIR / f"{run_id}.json"
        if not candidate.exists():
            return None
        return json.loads(candidate.read_text(encoding="utf-8"))

    manifests = sorted(RUN_MANIFEST_DIR.glob("*.json"))
    if not manifests:
        return None
    return json.loads(manifests[-1].read_text(encoding="utf-8"))


