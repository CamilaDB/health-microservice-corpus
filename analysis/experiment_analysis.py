def build_h2_coverage_table(df: pd.DataFrame) -> pd.DataFrame:
    """
    H2 primary evidence table: statement/branch coverage by model x
    strategy x CCM band.

    Every cell distinguishes three states explicitly, never silently
    zero-filled:
      - attempted_observations: every row in the cell, regardless of
        outcome (the true denominator for "how many targets exist here").
      - fully_skipped_observations: attempted but not measurable (every
        generated test was skip-repaired away -- see load_results).
      - verified_observations / distinct_functions: the population the
        mean/median/IQR columns are actually computed over. A cell with
        attempted_observations > 0 but verified_observations == 0 has
        NaN coverage columns, not 0 -- "not measured" is not "zero
        quality".
    """
    empty_cols = [
        "model", "strategy", "ccm_band",
        "attempted_observations", "fully_skipped_observations",
        "verified_observations", "distinct_functions",
        "mean_statement_coverage", "median_statement_coverage",
        "q1_statement_coverage", "q3_statement_coverage",
        "mean_branch_coverage", "median_branch_coverage",
        "q1_branch_coverage", "q3_branch_coverage",
    ]
    if "ccm" not in df.columns:
        return pd.DataFrame(columns=empty_cols)

    banded = _add_ccm_band(df)
    keys = ["model", "strategy", "ccm_band"]

    attempted = banded.groupby(keys, dropna=False, observed=False).agg(
        attempted_observations=("fn_id", "size"),
        fully_skipped_observations=("fully_skipped", "sum"),
    ).reset_index()

    verified = banded[banded["verified_eligible"]]
    measured = verified.groupby(keys, dropna=False, observed=False).agg(
        verified_observations=("fn_id", "size"),
        distinct_functions=("fn_id", "nunique"),
        mean_statement_coverage=("fn_statements_pct", "mean"),
        median_statement_coverage=("fn_statements_pct", "median"),
        q1_statement_coverage=("fn_statements_pct", lambda s: s.quantile(0.25)),
        q3_statement_coverage=("fn_statements_pct", lambda s: s.quantile(0.75)),
        mean_branch_coverage=("fn_branches_pct", "mean"),
        median_branch_coverage=("fn_branches_pct", "median"),
        q1_branch_coverage=("fn_branches_pct", lambda s: s.quantile(0.25)),
        q3_branch_coverage=("fn_branches_pct", lambda s: s.quantile(0.75)),
    ).reset_index()

    table = attempted.merge(measured, on=keys, how="left")
    table["attempted_observations"] = table["attempted_observations"].fillna(0).astype(int)
    table["fully_skipped_observations"] = table["fully_skipped_observations"].fillna(0).astype(int)
    table["verified_observations"] = table["verified_observations"].fillna(0).astype(int)
    table["distinct_functions"] = table["distinct_functions"].fillna(0).astype(int)
    for col in [c for c in table.columns if "coverage" in c]:
        table[col] = table[col].round(2)
    return table.sort_values(["model", "strategy", "ccm_band"]).reset_index(drop=True)[empty_cols]


def build_h2_coverage_by_model_ccm(df: pd.DataFrame) -> pd.DataFrame:
    """
    build_h2_coverage_table collapsed across strategy -- the population
    behind Figure H2-A. Strategy-level detail remains available in
    build_h2_coverage_table for readers who need it.
    """
    columns = ["model", "ccm_band", "verified_observations", "distinct_functions",
               "mean_statement_coverage", "mean_branch_coverage"]
    if "ccm" not in df.columns:
        return pd.DataFrame(columns=columns)

    banded = _add_ccm_band(df)
    verified = banded[banded["verified_eligible"]]
    table = verified.groupby(["model", "ccm_band"], dropna=False, observed=False).agg(
        verified_observations=("fn_id", "size"),
        distinct_functions=("fn_id", "nunique"),
        mean_statement_coverage=("fn_statements_pct", "mean"),
        mean_branch_coverage=("fn_branches_pct", "mean"),
    ).reset_index()
    table["verified_observations"] = table["verified_observations"].astype(int)
    table["distinct_functions"] = table["distinct_functions"].astype(int)
    for col in ("mean_statement_coverage", "mean_branch_coverage"):
        table[col] = table[col].round(2)
    return table.sort_values(["model", "ccm_band"]).reset_index(drop=True)[columns]


def build_h2_smell_table(smell_df: pd.DataFrame) -> pd.DataFrame:
    """
    H2 secondary/complementary evidence (Option A): assertion_roulette_rate
    by model x strategy x CCM band, over measurable observations only
    (it_active > 0). unmeasurable_observations makes fully-skipped
    functions visible per cell instead of silently averaging them toward
    a "clean" 0% smell rate.

    Kept as a table, not promoted to a figure: this dataset shows no clear
    CCM-associated trend in assertion_roulette_rate (see the technical
    report) -- reported honestly as a negative/inconclusive finding rather
    than forced into a chart.
    """
    columns = ["model", "strategy", "ccm_band", "total_observations", "unmeasurable_observations",
               "measurable_observations", "distinct_functions",
               "mean_assertion_roulette_rate", "median_assertion_roulette_rate"]
    if smell_df.empty or "ccm" not in smell_df.columns:
        return pd.DataFrame(columns=columns)

    banded = smell_df.copy()
    banded["ccm_band"] = pd.cut(banded["ccm"], bins=CCM_BINS, labels=CCM_LABELS, right=False)
    keys = ["model", "strategy", "ccm_band"]

    all_counts = banded.groupby(keys, dropna=False, observed=False).agg(
        total_observations=("fn_id", "size"),
        unmeasurable_observations=("measurable", lambda s: int((~s).sum())),
    ).reset_index()

    measurable = banded[banded["measurable"]]
    rates = measurable.groupby(keys, dropna=False, observed=False).agg(
        measurable_observations=("fn_id", "size"),
        distinct_functions=("fn_id", "nunique"),
        mean_assertion_roulette_rate=("assertion_roulette_rate", "mean"),
        median_assertion_roulette_rate=("assertion_roulette_rate", "median"),
    ).reset_index()

    table = all_counts.merge(rates, on=keys, how="left")
    table["total_observations"] = table["total_observations"].fillna(0).astype(int)
    table["unmeasurable_observations"] = table["unmeasurable_observations"].fillna(0).astype(int)
    table["measurable_observations"] = table["measurable_observations"].fillna(0).astype(int)
    table["distinct_functions"] = table["distinct_functions"].fillna(0).astype(int)
    for col in ("mean_assertion_roulette_rate", "median_assertion_roulette_rate"):
        table[col] = table[col].round(2)
    return table.sort_values(keys).reset_index(drop=True)[columns]


def build_top_functions(df: pd.DataFrame) -> pd.DataFrame:
    top = df[df["verified_eligible"]][
        ["model", "strategy", "module", "function", "ccm", "total_tests", "passed_tests", "fn_functions_pct"]
    ].copy()
    top = top.sort_values(["model", "strategy", "total_tests"], ascending=[True, True, False]).reset_index(drop=True)
    return top


